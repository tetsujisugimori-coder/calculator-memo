import { generateRestorePlan, PLAN_RULE_VERSION, type PlanStatus, type RestorePlan } from './selective-restore-plan';
import { parseSelectionBackup, parseSelectionCurrent, samePreviewStructure, type PreviewItem } from './selection-preview';
import { parseStrictJsonSource, validateRestoreRaw, type JsonSourceNode } from './restore-validation';
import { applySourceEdits, sourceProperty, type SourceEdit, type PreservedRange } from './json-source-edit';

export const SAFETY_RULE_VERSION = 1;
export type SafetyContext = {
  backupText: string; backupIdentity: string; currentRaw: string | null; selectedKeys: readonly string[];
  generation: number; epoch: number; planRuleVersion: number; safetyRuleVersion: number; unsaved: boolean; blockedReason?: string;
};
export type SafetyCandidate = {
  status: PlanStatus; executionAllowed: false; reasons: string[]; unknowns: string[];
  raw: string | null; edits: SourceEdit[]; preserved: PreservedRange[]; unchangedKeys: string[];
  context: SafetyContext;
};
const canonical = (keys: readonly string[]) => [...keys].sort();
const sameKeys = (a: readonly string[], b: readonly string[]) => samePreviewStructure(canonical(a), canonical(b));
const sameContext = (a: SafetyContext, b: SafetyContext) => a.backupText === b.backupText && a.backupIdentity === b.backupIdentity && a.currentRaw === b.currentRaw && sameKeys(a.selectedKeys, b.selectedKeys) && a.generation === b.generation && a.epoch === b.epoch && a.planRuleVersion === b.planRuleVersion && a.safetyRuleVersion === b.safetyRuleVersion && a.unsaved === b.unsaved && a.blockedReason === b.blockedReason;
function collection(root: JsonSourceNode, category: PreviewItem['category']): JsonSourceNode | undefined {
  if (category === 'history' || category === 'notes') return sourceProperty(root, category);
  if (category === 'executions') return sourceProperty(root, 'formulaExecutions');
  const parent = sourceProperty(root, category === 'formulas' ? 'formulaLibrary' : 'formulaReports');
  return parent && sourceProperty(parent, 'entries');
}
function locate(root: JsonSourceNode, item: PreviewItem): JsonSourceNode | undefined {
  // Keys are generated by the strict preview parser, never supplied by an ID.
  const match = /^(history|notes|formulas|executions|reports):(\d+)$/.exec(item.key);
  if (!match || match[1] !== item.category) return undefined;
  const array = collection(root, item.category);
  return array?.kind === 'array' ? array.children[Number(match[2])] : undefined;
}

/** Stage 3A pure preparation. The Stage 2 plan remains unchanged and execution is
 * always forbidden. A fresh plan independently checks IDs, containment and refs. */
export function generateSafetyCandidate(context: SafetyContext, suppliedPlan: RestorePlan): SafetyCandidate {
  const result: SafetyCandidate = { status: 'UNKNOWN', executionAllowed: false, reasons: [], unknowns: [], raw: null, edits: [], preserved: [], unchangedKeys: [], context: { ...context, selectedKeys: canonical(context.selectedKeys) } };
  const stop = (status: PlanStatus, message: string) => { result.status = status; result.reasons.push(message); return result; };
  if (context.planRuleVersion !== PLAN_RULE_VERSION || suppliedPlan.ruleVersion !== PLAN_RULE_VERSION || context.safetyRuleVersion !== SAFETY_RULE_VERSION || suppliedPlan.status === 'STALE') return stop('STALE', '計画規則・安全規則または計画が失効しています。');
  if (context.unsaved || context.blockedReason) return stop('BLOCKED', context.blockedReason || '未保存編集または保存待ちがあり、実行準備を禁止します。');
  if (context.currentRaw === null) return stop('BLOCKED', '保存キーがありません。設定やcollectionは推測生成しません。');
  if (!sameKeys(context.selectedKeys, suppliedPlan.items.map(item => item.key))) return stop('STALE', '計画と選択集合が一致しません。');
  if (!context.selectedKeys.length || new Set(context.selectedKeys).size !== context.selectedKeys.length) return stop('BLOCKED', '空選択・重複選択は受理しません。');
  try {
    const backup = parseSelectionBackup(context.backupText), current = parseSelectionCurrent(context.currentRaw);
    if (!backup.ok || !current.ok) return stop('BLOCKED', !backup.ok ? backup.message : !current.ok ? current.message : '解析失敗');
    if (backup.preview.raw === null) return stop('UNKNOWN', 'バックアップ原文がありません。');
    const originalOrder = generateRestorePlan({ backup: backup.preview, current: current.preview, selectedKeys: suppliedPlan.items.map(item => item.key) });
    if (!samePreviewStructure(originalOrder, suppliedPlan)) return stop('STALE', '原文から再生成した計画と一致しません。明示再生成が必要です。');
    const fresh = generateRestorePlan({ backup: backup.preview, current: current.preview, selectedKeys: canonical(context.selectedKeys) });
    // Stage 2 adds a lexical execution prohibition without changing row.operation.
    // We do not remove that prohibition or promote its global status to PASS.
    for (const row of fresh.items) {
      if (row.operation === 'BLOCKED') result.reasons.push(...row.blockedReasons);
      if (row.operation === 'UNKNOWN' || row.unknowns.length) result.unknowns.push(...row.unknowns, `${row.key}: 完全検証できません。`);
    }
    if (fresh.counts.missingReferences) result.reasons.push('未選択項目を含む復元後の参照先が欠落しています。');
    if (fresh.counts.unknownReferences === null || fresh.counts.unknownReferences > 0) result.unknowns.push('復元後参照が不明・曖昧・未対応です。');
    if (result.reasons.length || result.unknowns.length || fresh.candidate.status !== 'PASS') return stop(result.reasons.length ? 'BLOCKED' : 'UNKNOWN', '禁止・不明の根拠を保持し、部分的な候補を成功としません。');
    const before = parseStrictJsonSource(context.currentRaw), source = parseStrictJsonSource(backup.preview.raw);
    const additions = new Map<JsonSourceNode, { keys: string[]; texts: string[] }>();
    for (const row of [...fresh.items].sort((a, b) => a.key < b.key ? -1 : a.key > b.key ? 1 : 0)) {
      if (row.coveredBy) continue;
      if (row.proposedOperation === 'UNCHANGED') { result.unchangedKeys.push(row.key); continue; }
      if (!row.category || !['history', 'notes', 'formulas', 'executions', 'reports'].includes(row.category)) return stop('BLOCKED', '子単独・設定・未知領域の編集は未対応です。');
      const item = backup.preview.items.find(item => item.key === row.key)!;
      const origin = locate(source.root, item);
      const targetArray = collection(before.root, item.category);
      if (!origin || targetArray?.kind !== 'array') return stop('BLOCKED', '既存配列と原文位置を同定できません。欠落collectionは生成しません。');
      const replacement = backup.preview.raw.slice(origin.start, origin.end);
      if (row.proposedOperation === 'ADD') {
        const entry = additions.get(targetArray) ?? { keys: [], texts: [] };
        entry.keys.push(row.key); entry.texts.push(replacement); additions.set(targetArray, entry);
      } else if (row.proposedOperation === 'REPLACE') {
        const targets = current.preview.items.filter(target => target.identity === item.identity);
        const target = targets.length === 1 ? locate(before.root, targets[0]) : undefined;
        if (!target) return stop('BLOCKED', '置換対象を一意に同定できません。');
        result.edits.push({ start: target.start, end: target.end, expected: context.currentRaw.slice(target.start, target.end), replacement, keys: [row.key] });
      } else return stop('UNKNOWN', '対応操作を確認できません。');
    }
    for (const [array, entry] of additions) {
      // Insert before existing trailing whitespace; keep every original code unit.
      const offset = array.children.at(-1)?.end ?? array.start + 1;
      result.edits.push({ start: offset, end: offset, expected: '', replacement: (array.children.length ? ',' : '') + entry.texts.join(','), keys: entry.keys });
    }
    result.edits.sort((a, b) => a.start - b.start || a.end - b.end);
    const edited = applySourceEdits(context.currentRaw, result.edits);
    const checked = validateRestoreRaw(edited.raw), preview = parseSelectionCurrent(edited.raw);
    if (!checked.ok || !preview.ok || preview.preview.validation !== 'valid') return stop('BLOCKED', '候補の厳格保存形式・数値検証に失敗しました。');
    if (!samePreviewStructure(parseStrictJsonSource(edited.raw).value, fresh.candidate.data)) return stop('UNKNOWN', '区間編集候補と構造計画が一致しません。');
    result.raw = edited.raw; result.preserved = edited.preserved; result.status = 'PASS';
    result.reasons.push('対応範囲内の原文保持・候補生成の事前検証PASS。実行許可ではありません。');
    return result;
  } catch (cause) { return stop('BLOCKED', cause instanceof Error ? cause.message : '原文保持を検証できません。'); }
}

export type PreflightResult = { status: PlanStatus; executionAllowed: false; reasons: string[] };
/** Two fresh reads surrounding recomputation; no storage mutation capability.
 * Reader must provide a monotonic epoch for observed events. Unobserved ABA and
 * the gap after this function returns remain unsolved, so this never authorizes IO. */
export function revalidateSafety(candidate: SafetyCandidate, read: () => SafetyContext): PreflightResult {
  const fail = (status: PlanStatus, reason: string): PreflightResult => ({ status, executionAllowed: false, reasons: [reason] });
  try {
    const first = read();
    const before: SafetyContext = { ...first, selectedKeys: [...first.selectedKeys] };
    if (!sameContext(candidate.context, before)) return fail('STALE', '原文・ファイル識別・選択・世代・規則・編集状態が失効しました。');
    const b = parseSelectionBackup(before.backupText), c = parseSelectionCurrent(before.currentRaw);
    if (!b.ok || !c.ok) return fail('BLOCKED', '直前の入力を解析できません。');
    const plan = generateRestorePlan({ backup: b.preview, current: c.preview, selectedKeys: canonical(before.selectedKeys) });
    const rebuilt = generateSafetyCandidate(before, plan);
    const last = read();
    const after: SafetyContext = { ...last, selectedKeys: [...last.selectedKeys] };
    if (!sameContext(before, after) || !sameContext(candidate.context, after)) return fail('STALE', '直前検証中に前提が変更されました。');
    if (rebuilt.status !== 'PASS') return { status: rebuilt.status, executionAllowed: false, reasons: [...rebuilt.reasons, ...rebuilt.unknowns] };
    if (candidate.status !== 'PASS' || candidate.executionAllowed !== false || candidate.raw !== rebuilt.raw || !samePreviewStructure(candidate.edits, rebuilt.edits) || !samePreviewStructure(candidate.preserved, rebuilt.preserved)) return fail('BLOCKED', '保存候補・原文保持証拠が再生成結果と一致しません。');
    return fail('PASS', '直前再検証の観測条件のみPASS。実行禁止。CAS・非協調writer・通知なしABA・確認後競合は未解決です。');
  } catch { return fail('UNKNOWN', '保存領域・前提の読取り失敗。旧PASSを使用しません。'); }
}
