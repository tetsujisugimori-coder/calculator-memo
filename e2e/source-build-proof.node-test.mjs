import {test} from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,readdirSync,cpSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {build,resolveConfig} from 'vite';
import {sourceBuildProof,verifyBuildProof} from './source-build-proof.mjs';
const hash=b=>createHash('sha256').update(b).digest('hex');
const blob=b=>createHash('sha1').update(Buffer.from(`blob ${b.length}\0`)).update(b).digest('hex');
const fixture=mkdtempSync(join(tmpdir(),'calculator-build-source-'));
const git=(...args)=>execFileSync('git',args,{cwd:fixture,encoding:'utf8'}).trim();
writeFileSync(join(fixture,'main.ts'),"import {value} from './value.ts'; export const result:number=value+1;\n");
writeFileSync(join(fixture,'value.ts'),'export const value:number=2;\n');
writeFileSync(join(fixture,'index.html'),'<!doctype html><html><head></head><body><script type="module" src="/main.ts"></script></body></html>\n');
git('init','-q');git('config','core.autocrlf','false');git('add','.');git('-c','user.name=Source build fixture','-c','user.email=source-build@example.invalid','commit','-qm','finite build source');
const head=git('rev-parse','HEAD'),tree=git('rev-parse','HEAD^{tree}'),root=join(fixture,'proof');mkdirSync(root);
const before={head,tree,run:'independent-build',attempt:'1',capturedAt:new Date().toISOString(),entries:['main.ts','value.ts','index.html'].map(path=>{const b=readFileSync(join(fixture,path));return {path,size:b.length,sha256:hash(b),blob:blob(b)};})};
writeFileSync(join(root,'before.json'),JSON.stringify(before));
const oldRoot=process.env.SOURCE_PROOF_DIR,oldCwd=process.cwd();
try{
 process.chdir(fixture);process.env.SOURCE_PROOF_DIR=root;
 await build({configFile:false,logLevel:'silent',root:fixture,plugins:[sourceBuildProof('independent-lib')],build:{write:false,minify:false,lib:{entry:join(fixture,'main.ts'),formats:['es']}}});
 await build({configFile:false,logLevel:'silent',root:fixture,plugins:[sourceBuildProof('independent-html')],build:{write:false,minify:false}});
}finally{process.chdir(oldCwd);if(oldRoot===undefined)delete process.env.SOURCE_PROOF_DIR;else process.env.SOURCE_PROOF_DIR=oldRoot;}
const binding={head,run:before.run,attempt:before.attempt,requiredInputs:['main.ts','value.ts','index.html']};
const verify=(dir,b=binding)=>{const cwd=process.cwd();try{process.chdir(fixture);return verifyBuildProof(dir,b);}finally{process.chdir(cwd);}};
const clone=name=>{const dir=join(fixture,name);cpSync(root,dir,{recursive:true});return dir;};
const manifests=dir=>readdirSync(join(dir,'builds'));
const edit=(dir,file,fn)=>{const path=join(dir,'builds',file),r=JSON.parse(readFileSync(path));fn(r);writeFileSync(path,JSON.stringify(r));};
test('Vite normal: actual TypeScript transforms and HTML origin match Git; generated bytes preserved',()=>{
 const result=verify(root);assert.equal(result.status,'PASS');assert.equal(result.builds,2);assert.ok(result.outputs.some(e=>e.fileName==='index.html'));assert.ok(result.inputs.some(e=>e.path==='main.ts'&&e.kind==='vite-input'));
});
test('Vite preview config resolution does not fabricate an incomplete build record',async()=>{
 const previousRoot=process.env.SOURCE_PROOF_DIR,cwd=process.cwd(),count=manifests(root).length;
 try{
  process.chdir(fixture);process.env.SOURCE_PROOF_DIR=root;
  const resolved=await resolveConfig({configFile:false,root:fixture,logLevel:'silent',plugins:[sourceBuildProof('independent-preview')]},'serve','production','production',true);
  assert.equal(resolved.command,'serve');assert.equal(manifests(root).length,count,'preview-must-not-create-build-evidence');
 }finally{process.chdir(cwd);if(previousRoot===undefined)delete process.env.SOURCE_PROOF_DIR;else process.env.SOURCE_PROOF_DIR=previousRoot;}
});
test('Vite source substitution with self-consistent manifest is rejected against Git',()=>{
 const dir=clone('wrong-input'),name=manifests(dir)[0],bytes=Buffer.from('export const replacement=100;\n'),sha256=hash(bytes);writeFileSync(join(dir,'bytes',sha256+'.txt'),bytes);
 edit(dir,name,r=>Object.assign(r.inputs[0],{size:bytes.length,sha256,blob:blob(bytes)}));assert.throws(()=>verify(dir),/vite-input-git/);
});
test('Vite input raw mismatch remains UNKNOWN and is not accepted',()=>{
 const dir=clone('unknown');edit(dir,manifests(dir)[0],r=>{r.status='UNKNOWN';r.inputs[0].status='UNKNOWN';});assert.throws(()=>verify(dir),/vite-build-status/);
});
test('Vite actual earlier transform changing input is recorded UNKNOWN',async()=>{
 const dir=join(fixture,'actual-pre-transform');mkdirSync(dir);writeFileSync(join(dir,'before.json'),JSON.stringify({...before,capturedAt:new Date().toISOString()}));
 const previousRoot=process.env.SOURCE_PROOF_DIR,cwd=process.cwd();
 try{process.chdir(fixture);process.env.SOURCE_PROOF_DIR=dir;await build({configFile:false,logLevel:'silent',root:fixture,plugins:[{name:'independent-injected-change',enforce:'pre',transform(code,id){if(id.endsWith('/value.ts'))return code.replace('=2','=3');}},sourceBuildProof('changed-transform')],build:{write:false,minify:false,lib:{entry:join(fixture,'main.ts'),formats:['es']}}});}
 finally{process.chdir(cwd);if(previousRoot===undefined)delete process.env.SOURCE_PROOF_DIR;else process.env.SOURCE_PROOF_DIR=previousRoot;}
 const r=JSON.parse(readFileSync(join(dir,'builds',manifests(dir)[0])));assert.equal(r.status,'UNKNOWN');assert.equal(r.inputs.find(e=>e.path==='value.ts').status,'UNKNOWN');assert.throws(()=>verify(dir),/vite-build-status/);
});
test('Vite generated output body corruption is rejected',()=>{
 const dir=clone('bad-output'),r=JSON.parse(readFileSync(join(dir,'builds',manifests(dir)[0])));writeFileSync(join(dir,'bytes',r.outputs[0].sha256+'.txt'),'changed generated output');assert.throws(()=>verify(dir),/vite-byte-size|vite-byte-sha256/);
});
test('Vite build mixed HEAD or run is rejected',()=>{
 const dir=clone('wrong-head');edit(dir,manifests(dir)[0],r=>r.head='0'.repeat(40));assert.throws(()=>verify(dir),/vite-head/);assert.throws(()=>verify(root,{...binding,run:'other-run'}),/vite-run/);
});
test('Vite duplicate build records are rejected',()=>{
 const dir=clone('duplicate'),name=manifests(dir)[0];cpSync(join(dir,'builds',name),join(dir,'builds','copied.json'));assert.throws(()=>verify(dir),/duplicate-vite-build/);
});
test('Vite missing required input is rejected',()=>assert.throws(()=>verify(root,{...binding,requiredInputs:['not-observed.ts']}),/missing-vite-input/));
test('Vite completion must precede post-execution capture',()=>assert.throws(()=>verify(root,{...binding,after:'2000-01-01T00:00:00.000Z'}),/vite-post-capture-time/));
test('Vite output dependency cannot refer to uncaptured source',()=>{
 const dir=clone('uncaptured-module');edit(dir,manifests(dir)[0],r=>r.outputs[0].modules.push('uncaptured.ts'));assert.throws(()=>verify(dir),/vite-output-unobserved-module/);
});
test('Vite original normal remains accepted after all mutants',()=>assert.equal(verify(root).status,'PASS'));
